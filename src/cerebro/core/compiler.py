    def _call_ollama(self, prompt: str) -> str | None:
        payload = json.dumps(
            {"model": self._MODEL, "prompt": prompt, "stream": False},
            ensure_ascii=False,
        ).encode("utf-8")
        req = request.Request(
            self._OLLAMA_URL,
            data=payload,
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        try:
            with request.urlopen(req, timeout=120) as resp:
                raw = resp.read().decode("utf-8")
        except ConnectionError:
            raise
        except error.URLError as exc:
            if isinstance(exc.reason, ConnectionError):
                raise ConnectionError(str(exc)) from exc
            _print_error(f"Local LLM offline or request failed: {exc}")
            return None
        except error.HTTPError as exc:
            _print_error(f"Local LLM offline or request failed: {exc}")
            return None
        except OSError as exc:
            _print_error(f"Network I/O error talking to Ollama: {exc}")
            return None

        try:
            data = json.loads(raw)
        except json.JSONDecodeError as exc:
            _print_error(f"Ollama returned invalid JSON: {exc}")
            return None

        try:
            return str(data["response"]).strip()
        except (KeyError, TypeError) as exc:
            _print_error(f"Ollama JSON missing 'response' field: {exc}")
            return None

    def _call_llm(self, prompt: str) -> str | None:
        """Dispatch by API key env priority, then Ollama. Silent .env load from cwd."""
        env_path = os.path.join(os.getcwd(), ".env")
        try:
            if os.path.exists(env_path):
                with open(env_path, "r", encoding="utf-8") as env_file:
                    for raw_line in env_file:
                        line = raw_line.strip()
                        if not line or line.startswith("#"):
                            continue
                        key, _, value = line.partition("=")
                        key = key.strip()
                        value = value.strip().strip("\"'")
                        if key:
                            os.environ[key] = value
        except OSError:
            pass

        try:
            if os.environ.get("ANTHROPIC_API_KEY"):
                return self._call_anthropic(prompt)
            if os.environ.get("OPENAI_API_KEY"):
                return self._call_openai(prompt)
            if os.environ.get("GEMINI_API_KEY"):
                return self._call_gemini(prompt)
            if os.environ.get("GROQ_API_KEY"):
                return self._call_groq(prompt)
            try:
                return self._call_ollama(prompt)
            except ConnectionError:
                sys.stderr.write(
                    "[CEREBRO INFO] Memory not compiled. No LLM provider found. "
                    "Set ANTHROPIC_API_KEY, OPENAI_API_KEY, GEMINI_API_KEY, "
                    "GROQ_API_KEY, or ensure Ollama is running.\n"
                )
                sys.stderr.flush()
                return None
        except Exception as exc:
            _print_error(f"LLM routing failed: {exc}")
            return None

    def compile(self) -> dict[str, Any]:
        """
        Fuse unpushed diffs + Cursor chat into ``KNOWLEDGE_GRAPH.md`` under ``out_dir``.

        No-ops when there is no new diff text and no chat. Resolves ``out_dir`` to git root.
        """
        root = resolve_repo_root()
        self.out_dir = (self.out_dir if self.out_dir.is_absolute() else root / self.out_dir).resolve()
        self.out_dir.mkdir(parents=True, exist_ok=True)

        wiki_path = self.out_dir / "KNOWLEDGE_GRAPH.md"
        existing_wiki = self._existing_wiki_text(wiki_path)

        diff_text = read_unpushed_patch_text(root)
        chat_text = get_pending_intents(root)

        if not diff_text.strip() and not chat_text.strip():
            return {
                "status": "noop",
                "out_dir": str(self.out_dir),
                "has_diffs": False,
                "has_chat": False,
            }

        prompt = self._build_merge_prompt(existing_wiki, diff_text, chat_text)
        markdown = self._call_llm(prompt)
        if markdown is None:
            return {
                "status": "llm_unavailable",
                "out_dir": str(self.out_dir),
                "has_diffs": bool(diff_text.strip()),
                "has_chat": bool(chat_text.strip()),
            }

        if not markdown:
            _print_error("LLM returned an empty response; wiki not updated.")
            return {
                "status": "error",
                "out_dir": str(self.out_dir),
                "has_diffs": bool(diff_text.strip()),
                "has_chat": bool(chat_text.strip()),
            }

        try:
            wiki_path.write_text(markdown + "\n", encoding="utf-8")
            queue_path = root / ".cerebro" / "intent_queue.json"
            if queue_path.exists():
                try:
                    queue_path.write_text("[]\n", encoding="utf-8")
                except OSError:
                    pass
        except OSError as exc:
            _print_error(f"Failed to write wiki file: {exc}")
            return {
                "status": "error",
                "out_dir": str(self.out_dir),
                "has_diffs": bool(diff_text.strip()),
                "has_chat": bool(chat_text.strip()),
            }

        return {
            "status": "ok",
            "out_dir": str(self.out_dir),
            "file": str(wiki_path),
            "has_diffs": bool(diff_text.strip()),
            "has_chat": bool(chat_text.strip()),
        }

    @staticmethod
    def _is_quiet() -> bool:
        return bool(os.environ.get("CEREBRO_COMPILE_QUIET", "").strip())
